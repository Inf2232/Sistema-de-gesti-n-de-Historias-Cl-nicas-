def obtener_riesgo_oms(
    diabetes: bool,
    sexo: str,
    fuma: bool,
    edad: int,
    presion_sistolica: int,
    colesterol: float,
    tablas=riesgo_coronario
):
    # 1. Determinar el rango de edad
    rangos_edad = ["40-44", "45-49", "50-54", "55-59", "60-64", "65-69", "70-74"]
    rango_edad = None
    for r in rangos_edad:
        min_e, max_e = map(int, r.split('-'))
        if min_e <= edad <= max_e:
            rango_edad = r
            break
    if not rango_edad:
        raise ValueError("Edad fuera de rango para las tablas OMS (40-74 años)")

    # 2. Determinar el rango de presión sistólica
    if presion_sistolica < 120:
        rango_presion = "<120"
    elif 120 <= presion_sistolica <= 139:
        rango_presion = "120-139"
    elif 140 <= presion_sistolica <= 159:
        rango_presion = "140-159"
    elif 160 <= presion_sistolica <= 179:
        rango_presion = "160-179"
    else:
        rango_presion = ">=180"

    # 3. Determinar el rango de colesterol (en mmol/L)
    if colesterol < 4:
        rango_colesterol = "<4"
    elif 4 <= colesterol <= 4.9:
        rango_colesterol = "4-4.9"
    elif 5 <= colesterol <= 5.9:
        rango_colesterol = "5-5.9"
    elif 6 <= colesterol <= 6.9:
        rango_colesterol = "6-6.9"
    else:
        rango_colesterol = ">=7"

    # 4. Buscar en el diccionario
    try:
        valor = tablas[diabetes][sexo][fuma][rango_edad][rango_presion][rango_colesterol]
        return valor
    except Exception as e:
        raise ValueError(f"No se encontró un valor para la combinación dada: {e}")

